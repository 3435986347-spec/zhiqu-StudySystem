-- 登录令牌的「纪元」：改密码（自己改、管理员重置）时 +1，之前签发的登录令牌一并失效。
--
-- 由来（2026-09-25）：JWT 是无状态的，原来改了密码，旧令牌照样能用到过期 —— 记住我的令牌是 30 天。
-- 而改密码正是账号被盗之后用户能做的那件事：改完了，偷走令牌的人还在。
-- 令牌里带着签发时的纪元（JwtUtils.EPOCH_CLAIM），过滤器每次请求本来就要读这一行（查是否被禁用），
-- 顺带比一下纪元，不多一次查询。用计数而不是「改密码的时间」：不牵扯任何时钟、时区。
-- 旧令牌没有这个声明，按 0 算 —— 上线时谁都不会被踢下线，直到他自己改一次密码。
ALTER TABLE sys_user
    ADD COLUMN token_epoch INT NOT NULL DEFAULT 0 COMMENT '改密码时 +1；令牌里的纪元与它不同就失效';
